import { describe, expect, it } from 'vitest'
import { config, route, type Scenario } from '../fixtures/har-builder.ts'
import { after, before } from '../fixtures/site-before-after.ts'
import { warningFixtures } from '../fixtures/warnings/index.ts'
import { parseHar, simulate } from '../src/engine/index.ts'
import type { Config } from '../src/engine/index.ts'
import { generateWorkbox } from '../src/export/workbox.ts'

const js = { language: 'js', precache: 'inline' } as const

interface Registered {
	match: (context: { url: URL, request: { destination: string, mode: string }, sameOrigin: boolean }) => unknown
	method: string
}

/**
 * Runs generated worker source against stand-ins for the Workbox functions
 * and returns what it registered, so the code itself can be put to the test.
 */
function load(source: string) {
	const routes: Registered[] = []
	const state = { routes, precached: null as unknown, defaultHandler: null as unknown }
	class Strategy {
		options: unknown

		constructor(options?: unknown) {
			this.options = options
		}
	}
	const stubs: Record<string, unknown> = {
		precacheAndRoute: (entries: unknown) => { state.precached = entries },
		registerRoute: (match: Registered['match'], _handler: unknown, method = 'GET') => { routes.push({ match, method }) },
		setDefaultHandler: (handler: unknown) => { state.defaultHandler = handler },
		ExpirationPlugin: Strategy,
		CacheableResponsePlugin: Strategy,
	}
	for (const name of ['CacheFirst', 'NetworkFirst', 'StaleWhileRevalidate', 'NetworkOnly', 'CacheOnly']) stubs[name] = Strategy
	const imported = [...source.matchAll(/^import \{ (.+) \} from/gm)].flatMap((found) => (found[1] ?? '').split(', '))

	new Function(...imported, source.replace(/^import .+$/gm, ''))(...imported.map((name) => stubs[name]))
	return state
}

/** Which route the generated code and the engine each give every request to. */
function compare(scenario: Scenario) {
	const har = parseHar(scenario.har)
	const result = simulate(har, scenario.config)
	const { routes } = load(generateWorkbox(scenario.config, js))
	const origin = new URL(scenario.config.origin).origin
	const pairs: [string | null, string | null][] = []
	har.requests.forEach((request, i) => {
		const by = result.requests[i]?.handledBy
		// The precache and the browser's own handling are not routes in the generated file.
		if (!by || by.kind === 'precache' || (by.kind === 'network' && by.reason !== 'unmatched' && by.reason !== 'method')) return
		const url = new URL(request.url)
		const context = {
			url,
			sameOrigin: url.origin === origin,
			request: { destination: request.destination === 'empty' ? '' : request.destination, mode: request.mode },
		}
		const winner = routes.findIndex((r) => r.method === request.method && Boolean(r.match(context)))
		pairs.push([by.kind === 'route' ? by.routeId : null, scenario.config.routes[winner]?.id ?? null])
	})
	return pairs
}

describe('generateWorkbox', () => {
	it('writes the fixed worker as readable Workbox code', () => {
		expect(generateWorkbox(after.config)).toBe(`// Generated by Service Worker Toolkit. It holds the caching rules only:
// add whatever else the worker needs (an offline fallback, skipWaiting,
// error handling) around them.
// Site: https://example.com

import { precacheAndRoute } from 'workbox-precaching'
import { registerRoute, setDefaultHandler } from 'workbox-routing'
import { CacheFirst, NetworkFirst, NetworkOnly } from 'workbox-strategies'
import { ExpirationPlugin } from 'workbox-expiration'
import { CacheableResponsePlugin } from 'workbox-cacheable-response'

declare const self: ServiceWorkerGlobalScope

// Precache: 3 files, answered before any route.
// self.__WB_MANIFEST is replaced with the list by the build (workbox-build injectManifest).
precacheAndRoute(self.__WB_MANIFEST)

// Routes are tried in the order they are registered, and the first match
// wins: a broad matcher takes the requests meant for the routes after it.

// 1. CDN images: cache first.
registerRoute(
	({ url, request }) =>
		url.origin === 'https://cdn.example.com'
		&& request.destination === 'image',
	new CacheFirst({
		cacheName: 'static-cache',
		fetchOptions: { mode: 'cors', credentials: 'omit' },
		matchOptions: { ignoreVary: true },
		plugins: [
			new ExpirationPlugin({
				maxEntries: 50,
				maxAgeSeconds: 2592000, // 30 days
				purgeOnQuotaError: true,
			}),
			new CacheableResponsePlugin({ statuses: [200] }),
		],
	}),
)

// 2. Build files: cache first.
registerRoute(
	({ url, sameOrigin }) =>
		sameOrigin
		&& url.pathname.startsWith('/dist/assets/')
		&& !url.pathname.startsWith('/dist/assets/favicons/'),
	new CacheFirst({
		cacheName: 'asset-cache',
		plugins: [
			new ExpirationPlugin({
				maxEntries: 60,
				maxAgeSeconds: 2592000, // 30 days
				purgeOnQuotaError: true,
			}),
			new CacheableResponsePlugin({ statuses: [200] }),
		],
	}),
)

// 3. Pages: network first.
registerRoute(
	({ url, request, sameOrigin }) =>
		request.mode === 'navigate'
		&& sameOrigin
		&& !url.pathname.startsWith('/actions/')
		&& !url.pathname.startsWith('/admin/')
		&& !url.pathname.startsWith('/cpresources/')
		&& !url.searchParams.has('utm')
		&& !url.searchParams.has('fbclid'),
	new NetworkFirst({
		cacheName: 'html-cache',
		plugins: [
			new ExpirationPlugin({
				maxEntries: 100,
				maxAgeSeconds: 604800, // 7 days
				purgeOnQuotaError: true,
			}),
			new CacheableResponsePlugin({ statuses: [200] }),
		],
	}),
)

// Everything no route matched: network only.
setDefaultHandler(new NetworkOnly())
`)
	})

	it('writes the precache list out when asked, and plain JavaScript', () => {
		const source = generateWorkbox(config({
			precache: { entries: [{ url: 'offline.html', revision: 'a1' }, { url: 'app-D4f8a1Zc.js' }], cleanUrls: false, ignoreParams: ['^v$'], directoryIndex: null },
		}), js)
		expect(source).not.toContain('declare const self')
		expect(source).toContain(`precacheAndRoute([
	{ url: 'offline.html', revision: 'a1' },
	{ url: 'app-D4f8a1Zc.js', revision: null },
], {
	ignoreURLParametersMatching: [/^v$/],
	directoryIndex: null,
	cleanURLs: false,
})`)
		expect(load(source).precached).toHaveLength(2)
	})

	it('leaves out purgeOnQuotaError when nothing would expire, and both options on a route with no cache', () => {
		const options = { purgeOnQuotaError: true, ignoreVary: true }
		const cached = generateWorkbox(config({ routes: [route('r', { strategy: 'cache-first', cacheName: 'c', options })] }))
		expect(cached).toContain('matchOptions: { ignoreVary: true },')
		expect(cached).not.toContain('ExpirationPlugin')
		const uncached = generateWorkbox(config({ routes: [route('r', { strategy: 'network-only', cacheName: '', options: { ...options, maxEntries: 5 } })] }))
		expect(uncached).toContain('new NetworkOnly(),')
		expect(uncached).not.toMatch(/ignoreVary|purgeOnQuotaError/)
	})

	it('imports only what it uses, and nothing for an empty configuration', () => {
		expect(generateWorkbox(config())).not.toContain('import')
		const source = generateWorkbox(config({ routes: [route('all', { strategy: 'stale-while-revalidate', cacheName: 'c' })] }))
		expect(source.match(/^import .+$/gm)).toEqual([
			'import { registerRoute } from \'workbox-routing\'',
			'import { StaleWhileRevalidate } from \'workbox-strategies\'',
		])
		expect(source).toContain('() => true,')
	})

	it('writes each kind of condition', () => {
		const source = generateWorkbox(config({
			routes: [route('r', {
				strategy: 'network-only',
				cacheName: 'unused',
				method: 'post',
				conditions: [
					{ type: 'origin', value: 'https://cdn.example.com/', negate: true },
					{ type: 'path-pattern', value: '^/a/b\\.(js|css)$', flags: 'ig' },
					{ type: 'destination', value: ['script', 'empty'] },
					{ type: 'mode', value: ['cors', 'no-cors'], negate: true },
					{ type: 'query-param', value: 'it\'s' },
					{ type: 'path-pattern', value: '(' },
				],
			})],
		}))
		expect(source).toContain(`	({ url, request }) =>
		url.origin !== 'https://cdn.example.com'
		&& /^\\/a\\/b\\.(js|css)$/i.test(url.pathname)
		&& ['script', ''].includes(request.destination)
		&& !['cors', 'no-cors'].includes(request.mode)
		&& url.searchParams.has('it\\'s')
		&& false /* invalid pattern: ( */,
	new NetworkOnly(),
	'POST',
)`)
		// A network-only route has no cache to name.
		expect(source).not.toContain('unused')
	})

	it('cannot be broken out of by a route name or origin', () => {
		const hostile: Config = config({
			origin: 'https://example.com\nalert(1)',
			routes: [route('r', { name: 'x\n*/ alert(1) //', strategy: 'cache-first', cacheName: '\'); alert(1); (\'' })],
		})
		const source = generateWorkbox(hostile, js)
		expect(source.split('\n').filter((line) => line.includes('alert')).every((line) => line.startsWith('//') || line.includes('cacheName: \'\\\'')))
			.toBe(true)
		expect(() => load(source)).not.toThrow()
	})
})

describe('the generated worker routes requests as the simulation says', () => {
	const scenarios: [string, Scenario][] = [
		['the worker before the fixes', before],
		['the worker after the fixes', after],
		...Object.entries(warningFixtures).flatMap(([code, pair]): [string, Scenario][] => [[`${code}, triggering`, pair.triggering], [`${code}, clean`, pair.clean]]),
	]

	it.each(scenarios)('%s', (_name, scenario) => {
		const pairs = compare(scenario)
		expect(pairs.length).toBeGreaterThan(0)
		expect(pairs.map(([, generated]) => generated)).toEqual(pairs.map(([simulated]) => simulated))
	})

	it('registers the default handler and the methods the configuration names', () => {
		const state = load(generateWorkbox(config({
			routes: [route('posts', { strategy: 'network-only', cacheName: '', method: 'POST' })],
			defaultHandler: { strategy: 'network-first', cacheName: 'fallback', options: { maxEntries: 5 } },
		}), js))
		expect(state.routes.map((r) => r.method)).toEqual(['POST'])
		expect(state.defaultHandler).toMatchObject({ options: { cacheName: 'fallback' } })
	})
})
